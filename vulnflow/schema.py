"""JSON Schema for machines.toml (`vulnflow schema`), for editor completion and checks.

A TOML language server such as taplo (LazyVim's TOML extra, VS Code's Even Better TOML)
reads the `#:schema ./schemas/machines.schema.json` line at the top of machines.toml and
then completes keys, offers the allowed values (exposure, criticality, scans, teams, ...)
and marks typos while you type. Built from the same constants and the inventory's teams
as the parser in config.py; tests check that the committed schema is up to date.
"""

from __future__ import annotations

import json
from typing import Any

from .config import (
    _CPE_PAIR_RE,
    _CPE_PART_RE,
    _NAME_RE,
    _REPO_RE,
    CRITICALITIES,
    EXPOSURES,
    INPUTS,
    MACHINE_KINDS,
    SCANS,
    Inventory,
)

EXPOSURE_HELP = {
    "internet": "reachable by anyone on the internet, before login",
    "external-auth": "reachable from outside, but only after login",
    "internal": "reachable from the internal network or user devices",
    "restricted": "segmented, admin-only, allow-listed (e.g. tailnet only)",
    "hostile-device": "runs on devices the organisation does not control",
}
INPUT_HELP = {
    "public": "anyone can supply input",
    "partner": "known external parties",
    "staff": "employees only",
}
CRITICALITY_HELP = {
    "critical": "harm to the public, customers or society",
    "high": "the organisation cannot do its core work",
    "normal": "everything else",
    "low": "test, sandbox, decommissioning",
}


def _enum(values: tuple[str, ...], helps: dict[str, str], what: str) -> dict[str, Any]:
    lines = "\n".join(f"- `{v}`: {helps[v]}" for v in values)
    return {"type": "string", "enum": [*values, ""], "description": f"{what}. Empty = unknown.\n\n{lines}"}


def machines_schema(inv: Inventory) -> dict[str, Any]:
    teams = sorted(inv.teams)
    team = {"type": "string", "enum": teams, "description": "Owning team (inventory/inventory.toml)."}
    context = {
        "exposure": _enum(EXPOSURES, EXPOSURE_HELP, "Who can reach it (docs/exposure.md)"),
        "input": _enum(INPUTS, INPUT_HELP, "Who controls the input it parses"),
        "criticality": _enum(CRITICALITIES, CRITICALITY_HELP, "How much it matters"),
        "eol": {"type": "boolean", "description": "No more patches from upstream."},
        "certified": {"type": "boolean", "description": "Changes follow a certification cycle."},
    }
    context_entry = {"type": "object", "additionalProperties": False, "properties": context}
    machine = {
        "team": team,
        "kind": {"type": "string", "enum": list(MACHINE_KINDS), "description": "linux or macos."},
        "scans": {
            "type": "array",
            "items": {"type": "string", "enum": list(SCANS)},
            "description": "What the agent scans (default: system on linux; brew, languages, apps on macos).",
        },
        "language_paths": {
            "type": "array",
            "items": {"type": "string"},
            "description": "Extra language tool directories, relative to $HOME.",
        },
        "containers_team": {**team, "description": "Owner of the container projects (default dev)."},
    }
    name = {"type": "object", "propertyNames": {"pattern": _NAME_RE.pattern}}
    return {
        "$schema": "http://json-schema.org/draft-07/schema#",
        "title": "vulnflow machines.toml",
        "description": "Your hosts, code, GitHub repositories and asset context. Generated by "
        "`vulnflow schema`; see machines.example.toml.",
        "type": "object",
        "additionalProperties": False,
        "properties": {
            "groups": {
                **name,
                "description": "Shared settings plus the hosts in them. Never exposure or "
                "criticality: one group can run a public service and an internal admin page.",
                "additionalProperties": {
                    "type": "object",
                    "additionalProperties": False,
                    "properties": {
                        **machine,
                        "hosts": {"type": "array", "items": {"type": "string", "pattern": _NAME_RE.pattern}},
                    },
                },
            },
            "hosts": {
                **name,
                "description": "Per-host settings and asset context of the host project.",
                "additionalProperties": {
                    "type": "object",
                    "additionalProperties": False,
                    "properties": {
                        **machine,
                        **context,
                        "group": {"type": "string", "description": "Join a group without being in its hosts list."},
                        "version": {"type": "string", "description": "Fixed DT project version."},
                        "images": {
                            "type": "object",
                            "description": "Asset context of the container projects on this host, by image "
                            "name, its last part, or a glob; `\"*\"` catches the rest.",
                            "additionalProperties": context_entry,
                        },
                    },
                },
            },
            "code": {
                **name,
                "description": "Application code (with its installed dependencies) on a host.",
                "additionalProperties": {
                    "type": "object",
                    "additionalProperties": False,
                    "required": ["host", "path"],
                    "properties": {
                        "host": {"type": "string"},
                        "path": {"type": "string", "description": "Absolute path on that host."},
                        "team": team,
                        "version": {"type": "string"},
                        **context,
                    },
                },
            },
            "github": {
                **name,
                "description": "GitHub repositories whose releases carry a CycloneDX SBOM.",
                "additionalProperties": {
                    "type": "object",
                    "additionalProperties": False,
                    "required": ["repo"],
                    "properties": {
                        "repo": {"type": "string", "pattern": _REPO_RE.pattern, "description": "owner/repo"},
                        "asset": {"type": "string", "description": "Glob on the release assets (default *.cdx.json)."},
                        "team": team,
                        **context,
                    },
                },
            },
            "projects": {
                "type": "object",
                "description": "Asset context for any other Dependency-Track project, by name (e.g. from CI).",
                "additionalProperties": context_entry,
            },
            "subscriptions": {
                "type": "object",
                "description": "Extra OpenCVE subscriptions per team.",
                "propertyNames": {"enum": teams},
                "additionalProperties": {
                    "type": "object",
                    "additionalProperties": False,
                    "properties": {
                        "vendors": {"type": "array", "items": {"type": "string", "pattern": _CPE_PART_RE.pattern}},
                        "products": {
                            "type": "object",
                            "propertyNames": {"pattern": _CPE_PART_RE.pattern},
                            "additionalProperties": {
                                "type": "array",
                                "items": {"type": "string", "pattern": _CPE_PART_RE.pattern},
                            },
                        },
                    },
                },
            },
            "cpe_map": {
                "type": "object",
                "description": "Formula, cask or bundle id -> NVD vendor:product.",
                "additionalProperties": {"type": "string", "pattern": _CPE_PAIR_RE.pattern},
            },
        },
    }


def render(inv: Inventory) -> str:
    return json.dumps(machines_schema(inv), indent=2) + "\n"
